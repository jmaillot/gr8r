/* Build-time generator for the static IANA zone list (Phase 44, D-03).
   Node ESM, zero dependencies (icons.mjs pattern). It enumerates
   Intl.supportedValuesOf('timeZone') at BUILD TIME ONLY — D-03 bans runtime
   client enumeration, so the output is a committed static module and the
   client never calls supportedValuesOf (offsets are computed live at render
   per D-02, so the list never goes stale on DST).
   Regenerate: node scripts/gen-timezones.mjs
   Deterministic: sorted by id, stable formatting — re-running produces a
   byte-identical file. */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.join(here, '..', 'src', 'lib', 'timezones.js');

const HEADER = `/* Generated by scripts/gen-timezones.mjs — committed static list (D-03).
   Offsets are computed live at render (D-02), so this list never goes stale on DST.
   Regenerate: node scripts/gen-timezones.mjs */

`;

const zones = [
  /* Build-time supplement (G-44-3, WR-02 residual): 'UTC' is absent from
     Intl.supportedValuesOf('timeZone') but is the single most likely
     hand-typed non-list value — without it, stored 'UTC' preselects Paris. */
  'UTC',
  ...Intl.supportedValuesOf('timeZone'),
]
  .map(id => {
    /* Display name = last IANA segment, underscores → spaces. Machine value
       (never an i18n catalogue entry — keeps npm run i18n:scan green, A3). */
    const name = id.split('/').pop().replace(/_/g, ' ');
    return { id, name };
  })
  .sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0));

/* Defensive integrity checks before emitting anything. */
const ids = zones.map(z => z.id);
if (new Set(ids).size !== ids.length) throw new Error('duplicate zone ids');
if (!zones.some(z => z.id === 'Europe/Paris')) throw new Error('Europe/Paris missing');
if (!ids.includes('UTC')) throw new Error('UTC missing (G-44-3 supplement)');
if (zones.some(z => z.name.includes('_'))) throw new Error('raw underscore leaked into a display name');
if (!ids.every(id => id === ids[ids.indexOf(id)])) throw new Error('unsorted output');
/* Round-trip drift guard (G-44-3, T-44-06): every emitted id must resolve to
   itself — catches ICU-variance cases where a supportedValuesOf id canonicalizes
   to something else and would preselect Paris in the combobox. */
for (const id of ids) {
  const canon = new Intl.DateTimeFormat('en-CA', { timeZone: id }).resolvedOptions().timeZone;
  if (canon !== id) throw new Error(`canonical-target drift: ${id} resolves to ${canon}`);
}

const body =
  HEADER +
  'export const TIMEZONES = [\n' +
  zones.map(z => `  { id: ${JSON.stringify(z.id)}, name: ${JSON.stringify(z.name)} },`).join('\n') +
  '\n];\n';

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, body);
console.log(`wrote ${path.relative(process.cwd(), OUT)} (${zones.length} zones)`);
