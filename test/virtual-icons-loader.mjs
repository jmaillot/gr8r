/* A loader that resolves the 'virtual:icons' specifier for the Node test runner.
   In the Vite dev/build pipeline, the virtual module is generated by a plugin;
   under plain Node, we stub it with an empty icon registry — the tests that
   exercise the modules depending on it (modals.js, inbox.js) only need the
   catalogue t() and the store, never an actual SVG path. */
export async function resolve(specifier, context, next) {
  if (specifier === 'virtual:icons') {
    return {
      shortCircuit: true,
      url: 'data:text/javascript,export const ICONS = {};',
    };
  }
  return next(specifier, context);
}
